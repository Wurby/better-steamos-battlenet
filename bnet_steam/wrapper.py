"""A launch-option wrapper that every game shortcut runs through.

Two problems, one script:

1. Proton's `waitforexitandrun` verb (what Steam uses) first waits for every Wine process in
   the prefix to exit. If the Battle.net launcher is open, the game would never start. When a
   launcher is running the wrapper uses Proton's `run` verb instead.
2. Games started with `-launcherlogin` or `-sso` (World of Warcraft, Diablo IV) ask the
   running, logged-in launcher for your session; on their own they land on a login screen and
   cannot connect. With `--login` the wrapper starts the launcher, waits until it reports it is
   logged in, runs the game, and closes a launcher it started so Steam does not keep showing
   the game as running.

Steam launch option:   run-game.sh [--login] %command% <game args>
"""
from pathlib import Path

# flags in a game's start command that mean "log in through the launcher"
LAUNCHER_FLAGS = ("-launcherlogin", "-sso")
SCRIPT_NAME = "run-game.sh"

SCRIPT = r'''#!/bin/bash
# Generated by bnet-steam; rewritten by `bnet-steam sync`, do not edit.
# Steam launch option:  run-game.sh [--login] %command% <game args>
set -u
LOGIN=0
if [ "${1:-}" = "--login" ]; then LOGIN=1; shift; fi

WORK=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$WORK/logs" 2>/dev/null
LOG="$WORK/logs/run-game.log"
[ -f "$LOG" ] && [ "$(stat -c %s "$LOG" 2>/dev/null || echo 0)" -gt 200000 ] && : >"$LOG"
log() { printf '%(%F %T)T %s\n' -1 "$*" >>"$LOG" 2>/dev/null; }

if [ -z "${STEAM_COMPAT_DATA_PATH:-}" ]; then
    log "STEAM_COMPAT_DATA_PATH is not set; running the game as is"
    exec "$@"
fi
PFX="$STEAM_COMPAT_DATA_PATH/pfx"
BNET="$PFX/drive_c/Program Files (x86)/Battle.net/Battle.net.exe"
BLOGS="$PFX/drive_c/users/steamuser/AppData/Local/Battle.net/Logs"
WAIT="${BNET_STEAM_WAIT:-90}"         # seconds to wait for the launcher to log in
POLL="${BNET_STEAM_POLL:-1}"          # seconds between checks
SETTLE="${BNET_STEAM_SETTLE:-2}"      # grace period after "Ready" before the game starts
PROC="${BNET_STEAM_PROC:-/proc}"      # tests point this at a fake process table
PROTON=""
for a in "$@"; do case "$a" in */proton) PROTON="$a"; break ;; esac; done

# A real launcher process: its command line STARTS with the Windows path. (A shell that merely
# mentions "Battle.net.exe" somewhere in its arguments must not count.)
launcher_running() {
    # one grep over every process (-z: argv elements are NUL-separated "lines"); forking per
    # process is far too slow, especially under Steam's LD_PRELOAD
    grep -aqiz '^C:\\Program Files (x86)\\Battle\.net\\Battle\.net\.exe' "$PROC"/[0-9]*/cmdline 2>/dev/null
}

# true when the newest launcher log (newer than file $1, if given) says it is logged in.
# The logs use Windows line endings, hence the tr.
launcher_ready() {
    local f
    if [ -n "${1:-}" ]; then
        f=$(find "$BLOGS" -maxdepth 1 -name 'battle.net-*.log' -newer "$1" 2>/dev/null | sort | tail -1)
    else
        f=$(find "$BLOGS" -maxdepth 1 -name 'battle.net-*.log' 2>/dev/null | sort | tail -1)
    fi
    [ -n "$f" ] || return 1
    [ "$(grep -a 'State changed to:' "$f" | tail -1 | tr -d '\r' | sed 's/.*State changed to: *//')" = "Ready" ]
}

if [ "$LOGIN" = 0 ] && ! launcher_running; then
    exec "$@"                          # nothing in the way: behave exactly as without a wrapper
fi

STARTED=0
MARK=""
log "game: ${*: -3}  (login=$LOGIN)"
log "argv: ${*:1:6}"
log "container: $([ -e /run/pressure-vessel ] && echo yes || echo no)  pid-visible-procs: $(ls "$PROC" 2>/dev/null | grep -c '^[0-9]')"
if launcher_running; then
    log "launcher already running"
elif [ -z "$PROTON" ] || [ ! -f "$BNET" ]; then
    log "cannot start the launcher (proton='$PROTON' launcher exe present: $([ -f "$BNET" ] && echo yes || echo no)); running the game anyway"
else
    MARK=$(mktemp)
    log "starting the launcher"
    "$PROTON" run "$BNET" >>"$LOG" 2>&1 &
    STARTED=1
fi

# wait whenever the launcher is up, or was just started (it may not show in the process
# table yet, so do not re-check that right after starting it)
if [ "$LOGIN" = 1 ] && { [ "$STARTED" = 1 ] || launcher_running; }; then
    ok=0
    t0=$SECONDS
    while [ $((SECONDS - t0)) -lt "$WAIT" ]; do
        if launcher_ready "$MARK"; then ok=1; break; fi
        sleep "$POLL"
    done
    if [ "$ok" = 1 ]; then
        log "launcher logged in after $((SECONDS - t0))s"
        sleep "$SETTLE"
    else
        log "launcher not logged in after ${WAIT}s; running the game anyway"
    fi
fi
[ -n "$MARK" ] && rm -f "$MARK"

# `waitforexitandrun` would wait for the launcher's Wine processes to exit before running the game
ARGS=("$@")
if [ "$STARTED" = 1 ] || launcher_running; then
    for i in "${!ARGS[@]}"; do
        if [ "${ARGS[$i]}" = waitforexitandrun ]; then
            ARGS[$i]=run
            log "launcher is up: using 'run' instead of 'waitforexitandrun'"
            break
        fi
    done
fi

"${ARGS[@]}"
rc=$?
log "game exited with $rc"

if [ "$STARTED" = 1 ]; then
    log "closing the launcher we started"
    "$PROTON" run taskkill /F /IM Battle.net.exe >>"$LOG" 2>&1
fi
exit "$rc"
'''


def needs_launcher(args):
    """True if a game's start command signs in through the launcher."""
    return any(t in LAUNCHER_FLAGS for t in args.split())


def ensure(env):
    """Write (or refresh) the wrapper script in our data dir; returns its path."""
    path = env.work / SCRIPT_NAME
    env.work.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != SCRIPT:
        path.write_text(SCRIPT)
    path.chmod(0o755)
    return path
