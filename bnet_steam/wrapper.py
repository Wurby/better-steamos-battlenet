"""A launch-option wrapper that every shortcut runs through.

1. Proton's `waitforexitandrun` verb (what Steam uses) first waits for every Wine process in the
   prefix to exit. If the Battle.net launcher is open, a game would never start. When a launcher
   is running the wrapper uses Proton's `run` verb instead.
2. With `--launcher-fix`, a shortcut that starts the launcher is redirected through
   launcher.bat (see battlenet.py), which tells the launcher it is not on a handheld before it
   starts, so it shows its normal UI. The shortcut itself still points at Battle.net.exe.

With no launcher running and no `--launcher-fix` it changes nothing.
Steam launch option:   run-game.sh [--launcher-fix] %command% <args>
"""

SCRIPT_NAME = "run-game.sh"

SCRIPT = r'''#!/bin/bash
# Generated by bnet-steam; rewritten by `bnet-steam sync`, do not edit.
# Steam launch option:  run-game.sh [--launcher-fix] %command% <args>
set -u
FIX=0
if [ "${1:-}" = "--launcher-fix" ]; then FIX=1; shift; fi
PROC="${BNET_STEAM_PROC:-/proc}"      # tests point this at a fake process table

# A real launcher process: its command line has an element that STARTS with the Windows path.
# (A shell that merely mentions "Battle.net.exe" somewhere in its arguments must not count.)
# One grep over every process: forking per process is far too slow under Steam's LD_PRELOAD.
launcher_running() {
    grep -aqiz '^C:\\Program Files (x86)\\Battle\.net\\Battle\.net\.exe' "$PROC"/[0-9]*/cmdline 2>/dev/null
}

if [ "$FIX" = 0 ] && ! launcher_running; then
    exec "$@"                          # nothing in the way: behave exactly as without a wrapper
fi

WORK=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$WORK/logs" 2>/dev/null
LOG="$WORK/logs/run-game.log"
[ -f "$LOG" ] && [ "$(stat -c %s "$LOG" 2>/dev/null || echo 0)" -gt 200000 ] && : >"$LOG"
log() { printf '%(%F %T)T %s\n' -1 "$*" >>"$LOG" 2>/dev/null; }

ARGS=("$@")

# `waitforexitandrun` would wait for the launcher's Wine processes to exit before running
if launcher_running; then
    for i in "${!ARGS[@]}"; do
        if [ "${ARGS[$i]}" = waitforexitandrun ]; then
            ARGS[$i]=run
            log "launcher is running: using 'run' instead of 'waitforexitandrun' (${*: -2})"
            break
        fi
    done
fi

# start the launcher through launcher.bat, which hides the "handheld" hardware first
if [ "$FIX" = 1 ]; then
    PFX="${STEAM_COMPAT_DATA_PATH:-/nonexistent}/pfx"
    CMD="$PFX/drive_c/windows/system32/cmd.exe"
    BAT="$PFX/drive_c/bnet-steam/launcher.bat"
    done_fix=0
    if [ -f "$CMD" ] && [ -f "$BAT" ]; then
        for i in "${!ARGS[@]}"; do
            case "${ARGS[$i]}" in
                */Battle.net.exe)
                    ARGS=("${ARGS[@]:0:$i}" "$CMD" /c 'C:\bnet-steam\launcher.bat' "${ARGS[@]:$((i + 1))}")
                    done_fix=1
                    log "starting the launcher through launcher.bat (generic board: no handheld UI)"
                    break ;;
            esac
        done
    fi
    [ "$done_fix" = 1 ] || log "launcher fix requested but not applied (cmd.exe/launcher.bat missing or no launcher exe in the command)"
fi

exec "${ARGS[@]}"
'''


def ensure(env):
    """Write (or refresh) the wrapper script in our data dir; returns its path."""
    path = env.work / SCRIPT_NAME
    env.work.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != SCRIPT:
        path.write_text(SCRIPT)
    path.chmod(0o755)
    return path
